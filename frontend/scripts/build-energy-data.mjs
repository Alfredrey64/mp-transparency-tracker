// Builds src/data/energyData.json for the Net zero and energy bills page.
//
//   node scripts/build-energy-data.mjs
//
// Sources (each an official release; the page names them). The links are found from GOV.UK's content API, so the script keeps working when a new release replaces the old one.
//   - DESNZ, Final UK greenhouse gas emissions statistics (1990 to the latest year): total and by sector, with progress against the carbon budgets and the Paris targets. DESNZ,
//     Provisional UK greenhouse gas emissions statistics (the year after).
//   - DESNZ, UK local authority and regional greenhouse gas emissions statistics: each nation and region's emissions by sector, with population, 2005 onward.
//   - DESNZ, Energy Trends table 5.1: electricity generated by fuel (TWh), annual, from 1998.
//   - DESNZ, Quarterly Energy Prices, Annual domestic energy bills (tables 2.2.1, 2.2.3, 2.3.1, 2.6.1) and international domestic electricity prices (table 5.6.1, from Eurostat).
//   - Ofgem, the energy price cap model (the "historical level tables"): what the default tariff cap is made of, each period since 2017.
//   - DESNZ, Fuel poverty trends (England, Low Income Low Energy Efficiency measure).
//   - ONS, consumer price index (all items, annual average) to put bills in today's money; the ONS series the site already holds for the monthly energy price rise.
//   - World Bank, World Development Indicators: greenhouse gas emissions per head, fossil fuel share of electricity, energy use per head, for how the UK compares.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readXlsx } from "../../xlsx-lite.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "../src/data/energyData.json");
const UA = { "User-Agent": "Mozilla/5.0 simple-politics" };
const round = (v, d = 1) => Math.round(v * 10 ** d) / 10 ** d;
const num = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null);
const getBuf = async (url) => {
  let last = null;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const r = await fetch(url, { headers: UA, redirect: "follow" });
    if (r.ok) return Buffer.from(await r.arrayBuffer());
    last = r.status;
    if (r.status < 500) break;
    await new Promise((x) => setTimeout(x, 1500 * (attempt + 1)));
  }
  throw new Error(`${url}: ${last}`);
};
const content = async (slug) => {
  const r = await fetch(`https://www.gov.uk/api/content${slug}`, { headers: UA });
  if (!r.ok) throw new Error(`GOV.UK ${slug}: ${r.status}`);
  return r.json();
};
// The newest release in a family: GOV.UK search, filtered to DESNZ statistics, sorted by the year in the slug.
async function latestRelease(query, slugTest) {
  const url = `https://www.gov.uk/api/search.json?q=${encodeURIComponent(query)}&count=40&fields=link&fields=public_timestamp&filter_organisations=department-for-energy-security-and-net-zero`;
  const results = (await (await fetch(url, { headers: UA })).json()).results.filter((r) => slugTest.test(r.link));
  if (!results.length) throw new Error(`No release found for ${query}`);
  results.sort((a, b) => b.public_timestamp.localeCompare(a.public_timestamp));
  return results[0].link;
}
const attachment = (page, test) => {
  const a = page.details.attachments.find((x) => x.url && test.test(`${x.title} ${x.url}`));
  if (!a) throw new Error(`No attachment matching ${test} on ${page.title}`);
  return a.url;
};
const book = async (url) => readXlsx(await getBuf(url));
const rowsOf = (wb, name) => (wb[name] ?? []).filter(Boolean);
const headerIndex = (rows, test) => rows.findIndex((r) => r.some((c) => test(String(c))));

// ---- Greenhouse gas emissions: national ---------------------------------------------------------------------------------------------------
const SECTORS = [
  ["Electricity supply total", "power", "Electricity supply"],
  ["Fuel supply total", "fuel", "Fuel supply"],
  ["Domestic transport total", "transport", "Transport"],
  ["Buildings and product uses total", "buildings", "Buildings and product uses"],
  ["Industry total", "industry", "Industry"],
  ["Agriculture total", "agriculture", "Agriculture"],
  ["Waste total", "waste", "Waste"],
  ["LULUCF total", "land", "Land use and forestry"],
];
async function emissions() {
  const finalSlug = await latestRelease("greenhouse gas emissions", /^\/government\/statistics\/final-uk-greenhouse-gas-emissions-statistics-1990-to-\d{4}$/);
  const finalPage = await content(finalSlug);
  const wb = await book(attachment(finalPage, /data tables.*\.xlsx/i));
  const t11 = rowsOf(wb, "1.1");
  const head11 = t11[headerIndex(t11, (c) => c === "Gas")];
  const yearCols = head11.map((c, i) => ({ c: Number(c), i })).filter((x) => x.c >= 1990);
  const years = yearCols.map((x) => x.c);
  const pick = (rows, label, fromCol = 1) => {
    const r = rows.find((x) => String(x[0]).trim() === label);
    if (!r) throw new Error(`No row ${label}`);
    return yearCols.map((x) => round(Number(r[x.i - 1 + fromCol]), 2));
  };
  const total = pick(t11, "Total greenhouse gas emissions");
  const gases = { co2: pick(t11, "Net CO2 emissions (emissions minus removals)"), ch4: pick(t11, "Methane (CH4)"), n2o: pick(t11, "Nitrous oxide (N2O)") };
  const hfc = pick(t11, "Hydrofluorocarbons (HFCs)");
  const pfc = pick(t11, "Perfluorocarbons (PFCs)");
  const sf6 = pick(t11, "Sulphur hexafluoride (SF6)");
  gases.fgas = hfc.map((v, i) => round(v + pfc[i] + sf6[i], 2));

  // Sectors: the "total" rows in table 1.2; the first columns hold labels, so find the year columns again.
  const t12 = rowsOf(wb, "1.2");
  const head12 = t12[headerIndex(t12, (c) => c === "TES sector")];
  const cols12 = head12.map((c, i) => ({ c: Number(c), i })).filter((x) => x.c >= 1990);
  const sectors = {};
  for (const [label, key, name] of SECTORS) {
    const r = t12.find((x) => String(x[0]).trim() === label);
    if (!r) throw new Error(`No sector row ${label}`);
    sectors[key] = { name, values: cols12.map((x) => round(Number(r[x.i]), 2)) };
  }
  // Power station fuel detail: coal's part of electricity supply emissions.
  const coal = t12.find((x) => String(x[2]).trim() === "Power stations - coal");
  const coalValues = coal ? cols12.map((x) => round(Number(coal[x.i]), 2)) : null;

  // Carbon budgets: 2.1 gives the first four (performance), the later two are set in law (legislation.gov.uk), written in src/data/energy.js.
  const t21 = rowsOf(wb, "2.1");
  const budgets = [];
  for (const id of ["CB1", "CB2", "CB3", "CB4"]) {
    const h = t21.find((r) => r[0] === id);
    const periodYears = h.slice(2, 7).map(String);
    const netRow = t21[t21.indexOf(h) + 1];
    const accountRow = t21[t21.indexOf(h) + 3];
    const target = t21[t21.indexOf(h) + 4]?.find((c) => typeof c === "number");
    const totalCol = h.indexOf(`${id} total`);
    budgets.push({ id, years: periodYears.map(Number), target, accountTotal: num(accountRow[totalCol]) ?? num(netRow[totalCol]), settled: id !== "CB4" });
  }

  // Provisional figure for the year after the final data (published first, in the spring).
  let provisional = null;
  try {
    const provSlug = await latestRelease("provisional greenhouse gas emissions", /^\/government\/statistics\/provisional-uk-greenhouse-gas-emissions-statistics-\d{4}$/);
    const provPage = await content(provSlug);
    const provWb = await book(attachment(provPage, /data tables.*\.xlsx/i));
    const p1 = rowsOf(provWb, "1a_GHG");
    const ph = p1[headerIndex(p1, (c) => c === "TES sector")];
    const last = ph.length - 1;
    const py = Number(String(ph[last]).replace(/\D/g, "").slice(0, 4));
    if (py > years.at(-1)) {
      const row = (label) => num(Number(p1.find((r) => String(r[0]).trim() === label)?.[last]));
      provisional = {
        year: py, total: round(row("Total greenhouse gas emissions"), 1), release: provPage.title, updated: provPage.public_updated_at.slice(0, 10),
        sectors: Object.fromEntries([["Electricity supply", "power"], ["Fuel supply", "fuel"], ["Domestic transport", "transport"], ["Buildings and product uses", "buildings"], ["Industry", "industry"], ["Agriculture", "agriculture"], ["Waste", "waste"], ["Land use, land use change and forestry", "land"]].map(([l, k]) => [k, round(row(l), 1)])),
      };
    }
  } catch (e) { console.warn("Provisional emissions not read:", e.message); }

  return { release: finalPage.title, updated: finalPage.public_updated_at.slice(0, 10), years, total, gases, sectors, powerCoal: coalValues, budgets, provisional };
}

// ---- Greenhouse gas emissions: regions -------------------------------------------------------------------------------------------------------
const REGION_KEYS = { "North East": "ne", "North West": "nw", "Yorkshire and the Humber": "yh", "East Midlands": "em", "West Midlands": "wm", "East of England": "east", London: "london", "South East": "se", "South West": "sw", Wales: "wales", Scotland: "scotland", "Northern Ireland": "ni" };
async function regionalEmissions() {
  const slug = await latestRelease("local authority regional greenhouse gas emissions", /^\/government\/statistics\/uk-local-authority-and-regional-greenhouse-gas-emissions-statistics-2005-to-\d{4}$/);
  const page = await content(slug);
  const wb = await book(attachment(page, /data tables \(Excel\)/i));
  const rows = rowsOf(wb, "1_1");
  const head = rows[headerIndex(rows, (c) => c === "Region/Country")];
  const col = (name) => head.indexOf(name);
  const C = { year: col("Calendar Year"), total: col("Grand Total"), pop: col("Population ('000s, mid-year estimate)"), domestic: col("Domestic Total"), transport: col("Transport Total"), industry: col("Industry Total"), commercial: col("Commercial Total"), public: col("Public Sector Total"), agri: col("Agriculture Total"), waste: col("Waste Total"), land: col("LULUCF Net Emissions") };
  const out = {};
  const years = new Set();
  for (const r of rows.slice(rows.indexOf(head) + 1)) {
    const label = String(r[0] ?? "");
    if (!label.endsWith(" Total") || label === "England Total" || label === "National Total") continue;
    const key = REGION_KEYS[label.replace(/ Total$/, "")];
    if (!key) continue;
    const y = r[C.year];
    years.add(y);
    (out[key] ??= {})[y] = Object.fromEntries(Object.entries(C).filter(([k]) => k !== "year").map(([k, i]) => [k, round(Number(r[i]), 1)]));
  }
  const ys = [...years].sort();
  const regions = Object.fromEntries(Object.entries(out).map(([k, byYear]) => [k, { years: ys, total: ys.map((y) => byYear[y].total), population: ys.map((y) => byYear[y].pop), domestic: ys.map((y) => byYear[y].domestic), transport: ys.map((y) => byYear[y].transport), industry: ys.map((y) => round(byYear[y].industry + byYear[y].commercial + byYear[y].public, 1)), agriculture: ys.map((y) => byYear[y].agri), waste: ys.map((y) => byYear[y].waste) }]));
  if (Object.keys(regions).length !== 12) throw new Error(`Expected 12 regions, got ${Object.keys(regions).length}`);
  return { release: page.title, updated: page.public_updated_at.slice(0, 10), years: ys, regions };
}

// ---- Electricity generated by fuel ---------------------------------------------------------------------------------------------------------------
async function electricity() {
  const slug = await latestRelease("energy trends electricity", /^\/government\/statistics\/electricity-section-5-energy-trends$/);
  const page = await content(slug);
  const wb = await book(attachment(page, /ET 5\.1 - quarterly/i));
  const rows = rowsOf(wb, "Annual");
  const start = rows.findIndex((r) => String(r[0]).startsWith("Table 5.1b"));
  const end = rows.findIndex((r, i) => i > start && String(r[0]).startsWith("Table 5.1c"));
  const head = rows[start + 1];
  const yearCols = head.map((c, i) => ({ c: parseInt(String(c), 10), i })).filter((x) => x.c >= 1998 && x.c < 2100);
  const block = rows.slice(start + 2, end).filter((r) => r[0] === "All generating companies");
  const get = (fuel) => {
    const r = block.find((x) => String(x[1]).trim() === fuel);
    if (!r) throw new Error(`No ${fuel} in 5.1b`);
    return yearCols.map((x) => (typeof r[x.i] === "number" ? round(r[x.i], 3) : 0));
  };
  const parts = {
    coal: get("Coal"), oil: get("Oil"), gas: get("Gas"), nuclear: get("Nuclear"), wind: get("Total wind"), solar: get("Solar"), hydro: get("Hydro (natural flow)"), bioenergy: get("Bioenergy"),
  };
  const total = get("Total all generating companies");
  const other = total.map((t, i) => round(t - Object.values(parts).reduce((a, v) => a + v[i], 0), 3));
  // Net imports, from the supplied table 5.1c (all generating companies, "Net imports" is part of major producers).
  const cStart = rows.findIndex((r) => String(r[0]).startsWith("Table 5.1c"));
  const cHead = rows[cStart + 1];
  const cCols = cHead.map((c, i) => ({ c: parseInt(String(c), 10), i })).filter((x) => x.c >= 1998 && x.c < 2100);
  const imp = rows.slice(cStart + 2).find((r) => r[0] === "Major power producers" && String(r[1]).trim() === "Net imports");
  const imports = imp ? cCols.map((x) => (typeof imp[x.i] === "number" ? round(imp[x.i], 3) : 0)) : null;
  return { release: page.title, updated: page.public_updated_at.slice(0, 10), years: yearCols.map((x) => x.c), fuels: { ...parts, other }, total, imports };
}

// ---- Household bills ------------------------------------------------------------------------------------------------------------------------------------
async function bills() {
  const page = await content("/government/statistical-data-sets/annual-domestic-energy-price-statistics");
  const urlOf = (code) => attachment(page, new RegExp(`QEP ${code.replace(".", "\\.")}\\)`));
  // Standard consumption bills, all payment types, all tariffs ("Overall: All Tariffs" is the last column).
  const series = async (code, sheet) => {
    const rows = rowsOf(await book(urlOf(code)), sheet);
    const head = rows[headerIndex(rows, (c) => c === "Year")];
    const colIx = head.findIndex((c) => /^Overall: All Tariffs/.test(String(c)));
    if (colIx < 0) throw new Error(`No overall column in ${code}`);
    const out = {};
    for (const r of rows.slice(rows.indexOf(head) + 1)) if (typeof r[0] === "number" && typeof r[colIx] === "number") out[r[0]] = round(r[colIx], 0);
    return out;
  };
  const elec = await series("2.2.1", "2.2.1");
  const gas = await series("2.3.1", "2.3.1");
  const years = Object.keys(elec).map(Number).filter((y) => gas[y] !== undefined).sort();

  // By region (electricity and gas), the "Overall" bill for each pricing area.
  const regional = async (code, sheet) => {
    const rows = rowsOf(await book(urlOf(code)), sheet);
    const head = rows[headerIndex(rows, (c) => c === "Year")];
    const bill = head.findIndex((c) => /^Overall: Bill/i.test(String(c)));
    const unit = head.findIndex((c) => /^Overall: Unit cost/i.test(String(c)));
    const out = {};
    for (const r of rows.slice(rows.indexOf(head) + 1)) {
      if (typeof r[0] !== "number" || typeof r[1] !== "string") continue;
      if (typeof r[bill] !== "number" || typeof r[unit] !== "number") throw new Error(`Missing bill or unit cost for ${r[1]} ${r[0]} in ${code}`);
      (out[r[1]] ??= {})[r[0]] = { bill: round(r[bill], 0), unit: round(r[unit], 1) };
    }
    return out;
  };
  const elecRegions = await regional("2.2.3", "2.2.3");
  const gasRegions = await regional("2.3.3", "2.3.3").catch(() => null);

  // What households spend on energy in total (ONS, via DESNZ 2.6.1), £ million a year.
  const spendRows = rowsOf(await book(urlOf("2.6.1")), "2.6.1");
  const sh = spendRows[headerIndex(spendRows, (c) => /^Year/.test(String(c)))];
  const colOf = (re) => sh.findIndex((c) => re.test(String(c)));
  const spend = { years: [], gas: [], electricity: [], vehicle: [], all: [] };
  for (const r of spendRows.slice(spendRows.indexOf(sh) + 1)) {
    if (typeof r[0] !== "number" || r[0] < 1990) continue;
    spend.years.push(r[0]); spend.gas.push(r[colOf(/^Gas/)]); spend.electricity.push(r[colOf(/^Electricity/)]); spend.vehicle.push(r[colOf(/^Vehicle Fuels/)]); spend.all.push(r[colOf(/^All fuel and power/)]);
  }
  return { release: page.title, updated: page.public_updated_at.slice(0, 10), years, electricity: years.map((y) => elec[y]), gas: years.map((y) => gas[y]), elecRegions, gasRegions, spend };
}

// Consumer price index, annual average (2015 = 100), straight from the ONS.
async function cpiAnnual() {
  const j = JSON.parse((await getBuf("https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/d7bt/mm23/data")).toString("utf8"));
  const out = {};
  for (const y of j.years) out[y.year] = Number(y.value);
  const latest = j.months.at(-1);
  return { annual: out, latest: { label: latest.label, value: Number(latest.value) } };
}

// ---- Ofgem: what the default tariff cap is made of -------------------------------------------------------------------------------------------
async function priceCap() {
  const html = await (await fetch("https://www.ofgem.gov.uk/energy-regulation/domestic-and-non-domestic/energy-pricing-rules/energy-price-cap/energy-price-cap-default-tariff-levels", { headers: UA })).text();
  const links = [...html.matchAll(/href="([^"]+\.xlsx)"/g)].map((m) => new URL(m[1], "https://www.ofgem.gov.uk").toString()).filter((u) => /default[-_]tariff[-_]cap[-_]level|price[-_]cap[-_]levels/i.test(u));
  if (!links.length) throw new Error("No price cap model found");
  const wb = await book(links[0]); // the newest period is listed first
  const rows = wb["1b Historical level tables"];
  if (!rows) throw new Error("No historical level tables");
  // The "Dual fuel (implied)" block under "Other Payment Method": typical consumption, one column per period.
  const titleRow = rows.findIndex((r) => r && r.includes("Dual fuel (implied)"));
  const startCol = rows[titleRow].indexOf("Dual fuel (implied)");
  const typical = rows.findIndex((r, i) => i > titleRow && r && r[startCol] === "Typical consumption");
  // Keep each period's column position: the sheet leaves a blank column between two periods.
  const header = rows[typical];
  const cols = [];
  for (let c = startCol + 1; c < header.length && c < startCol + 31; c += 1) if (/\d{4}/.test(String(header[c] ?? ""))) cols.push(c);
  const labels = cols.map((c) => header[c]);
  const take = (code) => {
    const r = rows.slice(typical + 1, typical + 20).find((x) => x && x[startCol] === code);
    if (!r) throw new Error(`No ${code} row in the cap model`);
    return cols.map((c) => (typeof r[c] === "number" ? r[c] : 0));
  };
  const parts = Object.fromEntries(["DF", "CM", "AA", "PC", "NC", "OC", "SMNCC", "IC", "PAAC", "PAP", "CO", "DRC", "EBIT", "HAP"].map((c) => [c, take(c)]));
  const exVat = take("Total_GB average");
  const incVat = take("Total inc VAT");
  const monthIx = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
  const periods = labels.map((l, i) => {
    const m = /^(\w{3})\w* (\d{4})/.exec(String(l));
    const end = /(\w{3})\w* (\d{4})\s*$/.exec(String(l));
    return {
      label: String(l).replace(/\s+/g, " ").replace("June", "Jun").replace("Sept", "Sep"), time: round(Number(m[2]) + monthIx[m[1]] / 12, 3),
      wholesale: round(parts.DF[i] + parts.CM[i] + parts.AA[i], 0), network: round(parts.NC[i], 0), policy: round(parts.PC[i], 0),
      operating: round(parts.OC[i] + parts.SMNCC[i] + parts.IC[i] + parts.PAAC[i] + parts.PAP[i] + parts.CO[i] + parts.DRC[i], 0),
      margin: round(parts.EBIT[i] + parts.HAP[i], 0), exVat: round(exVat[i], 0), incVat: round(incVat[i], 0), endYear: Number(end[2]),
    };
  });
  return { source: links[0], periods };
}

// ---- Electricity prices in the EU (Eurostat, via DESNZ) -------------------------------------------------------------------------------------
async function euPrices() {
  const page = await content("/government/statistical-data-sets/international-domestic-energy-prices");
  const wb = await book(attachment(page, /Domestic electricity prices in the EU/i));
  const rows = rowsOf(wb, "Annual incl tax");
  const head = rows[headerIndex(rows, (c) => c === "Customer size")];
  const idx = (name) => head.indexOf(name);
  const countries = head.slice(2).map((c, i) => ({ name: String(c), i: i + 2 })).filter((x) => x.name && !/median|rank|relative/i.test(x.name));
  const medium = rows.filter((r) => r[0] === "Medium" && typeof r[1] === "number");
  const years = medium.map((r) => r[1]);
  const byCountry = Object.fromEntries(countries.map((c) => [c.name, medium.map((r) => (typeof r[c.i] === "number" ? round(r[c.i], 2) : null))]));
  const med = idx("EU 27 plus UK median [Note 1]");
  const rank = idx("UK relative to EU 27 plus UK rank [Note 2]");
  return {
    release: page.title, updated: page.public_updated_at.slice(0, 10), years, byCountry, median: medium.map((r) => (typeof r[med] === "number" ? round(r[med], 2) : null)),
    ukRank: medium.map((r) => (typeof r[rank] === "number" ? r[rank] : null)),
  };
}

// ---- Fuel poverty (England) -----------------------------------------------------------------------------------------------------------------------------
async function fuelPoverty() {
  const slug = await latestRelease("fuel poverty trends", /^\/government\/statistics\/fuel-poverty-trends-\d{4}$/);
  const page = await content(slug);
  const wb = await book(attachment(page, /\(Excel\)/i));
  const rows = rowsOf(wb, "Table 1");
  const start = rows.findIndex((r) => r[0] === "Fuel poor");
  const poor = [];
  for (let i = start; i < rows.length; i += 1) {
    const r = rows[i];
    if (i > start && r[0]) break;
    if (typeof r[1] === "number") poor.push(r);
  }
  return {
    release: page.title, updated: page.public_updated_at.slice(0, 10), years: poor.map((r) => r[1]), households: poor.map((r) => r[2]), share: poor.map((r) => round(r[3], 1)), gap: poor.map((r) => round(r[5], 0)),
  };
}

// ---- World Bank: how the UK compares --------------------------------------------------------------------------------------------------------------------
const COUNTRIES = { WLD: "World", GBR: "United Kingdom", DEU: "Germany", FRA: "France", ITA: "Italy", ESP: "Spain", NLD: "Netherlands", POL: "Poland", SWE: "Sweden", DNK: "Denmark", NOR: "Norway", IRL: "Ireland", CAN: "Canada", USA: "United States", JPN: "Japan", KOR: "South Korea", AUS: "Australia", CHN: "China", IND: "India" };
const INDICATORS = { ghgTotal: "EN.GHG.ALL.MT.CE.AR5", ghgPerHead: "EN.GHG.ALL.PC.CE.AR5", fossilShare: "EG.ELC.FOSL.ZS", energyPerHead: "EG.USE.PCAP.KG.OE" };
async function compare() {
  const out = Object.fromEntries(Object.entries(COUNTRIES).map(([c, name]) => [c, { name }]));
  for (const [key, ind] of Object.entries(INDICATORS)) {
    const url = `https://api.worldbank.org/v2/country/${Object.keys(COUNTRIES).join(";")}/indicator/${ind}?format=json&date=2015:2026&per_page=3000`;
    const json = JSON.parse((await getBuf(url)).toString("utf8"));
    const latest = {};
    for (const r of json[1] ?? []) {
      if (r.value === null) continue;
      const y = Number(r.date);
      if (!latest[r.countryiso3code] || y > latest[r.countryiso3code].year) latest[r.countryiso3code] = { year: y, value: round(r.value, key === "energyPerHead" ? 0 : 2) };
    }
    for (const c of Object.keys(COUNTRIES)) out[c][key] = latest[c] ?? null;
  }
  return out;
}

// ---- The ONS monthly energy price rise the site already holds ---------------------------------------------------------------------------------------
function energyInflation() {
  const s = JSON.parse(fs.readFileSync(path.join(here, "../src/data/ons/prices.json"), "utf8")).series;
  const e = s.energy;
  if (!e) throw new Error("No energy series in prices.json");
  const pts = e.points.filter((p) => p[0] >= "2015-01");
  const t = (label) => round(Number(label.slice(0, 4)) + (Number(label.slice(5)) - 1) / 12, 3);
  return { months: pts.map((p) => p[0]), times: pts.map((p) => t(p[0])), rate: pts.map((p) => round(p[1], 1)), all: s.cpi.points.filter((p) => p[0] >= "2015-01").map((p) => round(p[1], 1)) };
}

async function main() {
  const data = { built: new Date().toISOString().slice(0, 10) };
  data.emissions = await emissions();
  data.regional = await regionalEmissions();
  data.power = await electricity();
  data.bills = await bills();
  data.cpi = await cpiAnnual();
  data.cap = await priceCap();
  data.eu = await euPrices();
  data.fuelPoverty = await fuelPoverty();
  data.compare = await compare();
  data.inflation = energyInflation();
  fs.writeFileSync(OUT, `${JSON.stringify(data)}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} kB): emissions to ${data.emissions.years.at(-1)}, power to ${data.power.years.at(-1)}, bills to ${data.bills.years.at(-1)}, regions to ${data.regional.years.at(-1)}`);
}
main().catch((e) => { console.error(e); process.exit(1); });
