import { BarRows, Caution, Panel, StackBars, Stats, TrendExplorer } from "./insight";
import { FACTS, SOURCES } from "../data/energy";
import { COMPARE_MEASURES, POWER_GROUPS, POWER_LAST, PW, compareRanking, firstYearBelow, groupShare, lowCarbonShare, mixYears, powerAt, round, shareAt, totalAt } from "../lib/energy";
import { ACCENT, group } from "../lib/energyStyle";
import { para } from "../lib/insightStyle";
import { ordinal } from "../lib/regionData";

// Net zero and energy bills, the electricity toggle: where the UK's electricity comes from, how the mix has changed since 1998, how far it is from the
// government's 2030 goal, and how the UK compares.

const GROUP_LINES = {
  fossil: { name: "Gas, coal and oil", color: "#C0561F" },
  renewables: { name: "Wind, solar, hydro and biomass", color: "#0E7490" },
  nuclear: { name: "Nuclear", color: "#7A5AF0" },
};
const shareSeries = (key) => PW.years.map((y) => groupShare(y)[key]);
const fuelLine = (key, name, color) => ({ name, color, years: PW.years, values: PW.fuels[key] });

function Mix() {
  const g = groupShare(POWER_LAST);
  return (
    <Panel id="h-np-mix" accent={ACCENT} title="Where our electricity comes from" lead={`The electricity generated in the UK each year, by what it was made from. In ${POWER_LAST} the UK generated ${group(totalAt(POWER_LAST))} terawatt-hours (TWh), a terawatt-hour being a billion units, or kilowatt-hours.`} sources={[SOURCES.electricity]}>
      <TrendExplorer
        accent={ACCENT}
        options={[
          { key: "share", label: "Share of electricity", governments: true, lines: Object.entries(GROUP_LINES).map(([k, l]) => ({ ...l, years: PW.years, values: shareSeries(k) })), offset: 0, yFormat: (v) => `${Math.round(v)}%`, captionFormat: (v) => `${v.toFixed(1)}%`, change: "pp", from: PW.years[0], to: POWER_LAST + 1, note: `Fossil fuels made ${groupShare(PW.years[0]).fossil}% of electricity in ${PW.years[0]} and ${g.fossil}% in ${POWER_LAST}. Renewables went from ${groupShare(PW.years[0]).renewables}% to ${g.renewables}%. Biomass includes burning wood pellets and waste, and counts as renewable in the official figures, though how green that is is debated.` },
          { key: "fuels", label: "By fuel", lines: [fuelLine("gas", "Gas", "#C0561F"), fuelLine("wind", "Wind", "#0E7490"), fuelLine("nuclear", "Nuclear", "#7A5AF0"), fuelLine("bioenergy", "Biomass and waste", "#6F8F2B"), fuelLine("coal", "Coal", "#4B5563"), fuelLine("solar", "Solar", "#C7871A")], offset: 0, yFormat: (v) => `${Math.round(v)}`, captionFormat: (v) => `${Math.round(v)} TWh`, change: "percent", from: PW.years[0], to: POWER_LAST + 1, note: "Terawatt-hours of electricity generated each year. Wind and solar are weather-dependent, so a calm or dull year lowers them." },
          { key: "wind", label: "Wind and solar", lines: [fuelLine("wind", "Wind", "#0E7490"), fuelLine("solar", "Solar", "#C7871A")], offset: 0, yFormat: (v) => `${Math.round(v)}`, captionFormat: (v) => `${Math.round(v)} TWh`, change: "percent", from: 2005, to: POWER_LAST + 1, note: "Terawatt-hours generated each year." },
          { key: "coal", label: "Coal and gas", lines: [fuelLine("coal", "Coal", "#4B5563"), fuelLine("gas", "Gas", "#C0561F")], offset: 0, yFormat: (v) => `${Math.round(v)}`, captionFormat: (v) => `${Math.round(v)} TWh`, change: "percent", from: PW.years[0], to: POWER_LAST + 1, note: `Coal fell from ${group(powerAt("coal", PW.years[0]))} TWh in ${PW.years[0]} to ${powerAt("coal", POWER_LAST)} in ${POWER_LAST}. Gas generation peaked at ${group(Math.max(...PW.fuels.gas))} TWh in ${PW.years[PW.fuels.gas.indexOf(Math.max(...PW.fuels.gas))]} and was ${group(powerAt("gas", POWER_LAST))} in ${POWER_LAST}.` },
        ]}
      />
    </Panel>
  );
}

function Then() {
  const rows = mixYears().map((y) => ({ label: String(y), text: `${group(totalAt(y))} TWh`, parts: POWER_GROUPS.map((p) => ({ name: p.name, value: round(powerAt(p.key, y), 1), colour: p.colour })).filter((p) => p.value > 0.2) }));
  return (
    <Panel id="h-np-then" title="The mix, then and now" lead="The same electricity, cut up by fuel in four years. Each bar is scaled to the year with the most." sources={[SOURCES.electricity]}>
      <StackBars rows={rows} label="Electricity generated by fuel in four years, TWh" format={(v) => `${Math.round(v)}`} legend={POWER_GROUPS.filter((p) => !["oil", "hydro", "other"].includes(p.key)).map((p) => ({ name: p.name, colour: p.colour }))} />
      <p style={para}>Total generation has fallen from its peak of {group(Math.max(...PW.total))} TWh in {PW.years[PW.total.indexOf(Math.max(...PW.total))]} to {group(totalAt(POWER_LAST))}, as homes and industry have become more efficient and some heavy industry has closed. Gas was {shareAt("gas", PW.years[0])}% of generation in {PW.years[0]}, {shareAt("gas", 2010)}% in 2010 and {shareAt("gas", POWER_LAST)}% in {POWER_LAST}. Wind was {shareAt("wind", 2010)}% in 2010 and {shareAt("wind", POWER_LAST)}% in {POWER_LAST}.</p>
    </Panel>
  );
}

function Goal() {
  const now = lowCarbonShare(POWER_LAST);
  const five = lowCarbonShare(POWER_LAST - 5);
  const perYearNow = round((now - five) / 5, 1);
  const perYearNeeded = round((95 - now) / (2030 - POWER_LAST), 1);
  const imports = PW.imports?.at(-1);
  return (
    <Panel id="h-np-goal" title="The 2030 goal" lead={FACTS.cleanPower} sources={[SOURCES.cleanPower, SOURCES.electricity]}>
      <Stats
        accent={ACCENT}
        items={[
          { value: `${now}%`, label: `Renewables and nuclear, ${POWER_LAST}`, note: `${five}% in ${POWER_LAST - 5}. Fossil fuels: ${groupShare(POWER_LAST).fossil}%`, spark: PW.years.map((y) => lowCarbonShare(y)) },
          { value: `${perYearNow} points`, label: "Added each year, on average", note: `${POWER_LAST - 5} to ${POWER_LAST}` },
          { value: `${perYearNeeded} points`, label: "A year needed to reach 95% by 2030", note: `If the same sources are counted. ${2030 - POWER_LAST} years left` },
        ]}
      />
      <p style={para}>
        The government&apos;s measure is for Great Britain, not the UK, in a typical year for weather, and counts carbon capture as clean as well as renewables and nuclear. The figures here are the UK&apos;s actual output for {POWER_LAST}, so they are close but not the same. The government has also said that a small amount of gas (up to 5% of generation) will stay as back-up for still, dark days.
      </p>
      {imports !== null && imports !== undefined && (
        <p style={para}>The UK also imports electricity through cables from other countries. Net imports were {Math.round(imports)} TWh in {POWER_LAST}, about {round((imports / totalAt(POWER_LAST)) * 100, 0)}% of what the UK generated. They are not counted in the shares above.</p>
      )}
      <Caution title="Why this matters for bills">
        Gas often sets the wholesale price of electricity, even when most of the power comes from other sources. Supporters of the goal say that makes bills depend less on gas as the share falls. Critics say the networks and back-up capacity needed cost a great deal and the price of getting there falls on bills. The Bills toggle shows what the figures say about each.
      </Caution>
    </Panel>
  );
}

function Abroad() {
  const m = COMPARE_MEASURES.fossilShare;
  const rows = compareRanking("fossilShare");
  const ukRank = rows.findIndex((r) => r.code === "GBR") + 1;
  return (
    <Panel id="h-np-compare" title="How the UK compares" lead={`${m.blurb} Countries are in order, highest first, with the latest year the World Bank has for each.`} sources={[SOURCES.worldBank]}>
      <BarRows
        label="Share of electricity from fossil fuels, by country" accent="#9CA3AF" max={100}
        rows={rows.map((r) => ({ label: r.name, note: String(r.year), value: r.value, text: m.format(r.value), tone: r.code === "GBR" ? ACCENT : "#9CA3AF", strong: r.code === "GBR" }))}
      />
      <p style={para}>The UK is {ordinal(ukRank)} highest of {rows.length} countries on this measure, at {m.format(rows.find((r) => r.code === "GBR").value)}. The highest is {rows[0].name} ({m.format(rows[0].value)}) and the lowest {rows.at(-1).name} ({m.format(rows.at(-1).value)}).</p>
      <Caution title="Why countries differ">France and Sweden rely on nuclear and hydro power, Norway on hydro, and Poland and India on coal. Where a country can build hydro dams, or has long had nuclear power, it starts well ahead. The latest year differs a little by country.</Caution>
    </Panel>
  );
}

export default function EnergyPower() {
  const gone = firstYearBelow("coal", 0.5);
  return (
    <div>
      <Mix />
      <Then />
      <Goal />
      <Abroad />
      <p style={{ ...para, marginTop: 14 }}>Coal supplied {shareAt("coal", PW.years[0])}% of the UK&apos;s electricity in {PW.years[0]} and {gone ? `almost none from ${gone}` : "very little today"}.</p>
    </div>
  );
}
