import { describe, it, expect } from "vitest";
import { readXls } from "./xls-lite.js";

describe("xls reader", () => {
  it("refuses anything that is not an old Excel file", () => {
    expect(() => readXls(Buffer.from("PK\u0003\u0004 this is a zip, not an xls, and long enough to have a header....................................................................................................................................................................................................................................................................................................................................................................................................................................................................................................................................................."))).toThrow(/Not an \.xls file/);
  });
});
